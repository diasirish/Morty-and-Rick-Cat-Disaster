"""Training entry point - modes (a) and (b). THIS FILE IS COMPLETE.

    python -m rl.train --render            # (a) learn WITH visualization
    python -m rl.train                     # (b) learn headless, full speed
    python -m rl.train --random-agent      # pipeline smoke test (works now)
    python -m rl.train --render --fps 50   # watch at human speed

Outputs land in runs/<run-name>/:
    episodes.csv     one row per episode (return, length, score, won, eps)
    model.pt         checkpoint, refreshed every --checkpoint-every steps
Watch learning live with:  tail -f runs/<run-name>/episodes.csv

============================ READ THIS LOOP ================================
The block marked "THE RL LOOP" below is the entire reinforcement-learning
interaction pattern - the same five lines that drive every value-based
agent ever trained:

    1. agent picks a button          a   = agent.select_action(obs, step)
    2. world reacts                  obs', r, end = env.step(a)
    3. agent remembers               agent.observe(obs, a, r, obs', end)
    4. agent maybe learns            agent.update(step)
    5. the world rolls on            obs = obs'

EXPERIENCE is generated by 1-2, MEMORY is 3, LEARNING happens inside 4
(a gradient step on a random minibatch of memories - see rl/agent.py).
Everything else in this file is bookkeeping: logging, checkpoints, pacing.
============================================================================
"""

import argparse
import csv
import os
import time

from .agent import DQNAgent, RandomAgent
from .wrappers import make_env


def parse_args():
    parser = argparse.ArgumentParser(description="Train an agent on Cat Disaster")
    parser.add_argument("--render", action="store_true",
                        help="open a window and draw every step (mode (a))")
    parser.add_argument("--fps", type=int, default=0,
                        help="throttle rendering to N steps/sec (0 = unthrottled)")
    parser.add_argument("--total-steps", type=int, default=500_000)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--character", default="morty", choices=["morty", "rick"])
    parser.add_argument("--frame-skip", type=int, default=4)
    parser.add_argument("--random-agent", action="store_true",
                        help="use the no-learning RandomAgent (smoke test)")
    parser.add_argument("--run-name", default=None,
                        help="subfolder under runs/ (default: auto)")
    parser.add_argument("--checkpoint-every", type=int, default=25_000)
    return parser.parse_args()


def main():
    args = parse_args()

    run_name = args.run_name or ("random" if args.random_agent else "dqn")
    run_dir = os.path.join("runs", run_name)
    os.makedirs(run_dir, exist_ok=True)
    csv_path = os.path.join(run_dir, "episodes.csv")
    ckpt_path = os.path.join(run_dir, "model.pt")

    env = make_env(render=args.render, seed=args.seed,
                   character=args.character, frame_skip=args.frame_skip)
    if args.random_agent:
        agent = RandomAgent(seed=args.seed)
    else:
        agent = DQNAgent()  # <- raises NotImplementedError until you write it

    csv_file = open(csv_path, "w", newline="")
    logger = csv.writer(csv_file)
    logger.writerow(["episode", "step", "return", "length", "score", "won", "epsilon"])

    obs, _ = env.reset(seed=args.seed)
    episode, ep_return, ep_len = 0, 0.0, 0
    t_start, t_step0 = time.perf_counter(), 0
    min_dt = 1.0 / args.fps if args.fps else 0.0
    t_last_frame = 0.0

    for step in range(1, args.total_steps + 1):
        # ----------------------- THE RL LOOP -----------------------------
        action = agent.select_action(obs, step)                       # 1
        next_obs, reward, terminated, truncated, info = env.step(action)  # 2
        agent.observe(obs, action, reward, next_obs, terminated)      # 3
        agent.update(step)                                            # 4
        obs = next_obs                                                # 5
        # ------------------------------------------------------------------

        ep_return += reward
        ep_len += 1

        if terminated or truncated:
            episode += 1
            eps = agent.epsilon(step) if hasattr(agent, "epsilon") else ""
            logger.writerow([episode, step, round(ep_return, 2), ep_len,
                             info["score"], info["won"], eps])
            csv_file.flush()
            if episode % 10 == 0:
                rate = (step - t_step0) / (time.perf_counter() - t_start)
                t_start, t_step0 = time.perf_counter(), step
                print(f"ep {episode:5d}  step {step:8d}  "
                      f"return {ep_return:7.2f}  score {info['score']:3d}  "
                      f"{'WON ' if info['won'] else ''}{rate:6.0f} steps/s")
            obs, _ = env.reset()
            ep_return, ep_len = 0.0, 0

        if step % args.checkpoint_every == 0:
            agent.save(ckpt_path)

        if args.render and min_dt:
            now = time.perf_counter()
            sleep = min_dt - (now - t_last_frame)
            if sleep > 0:
                time.sleep(sleep)
            t_last_frame = time.perf_counter()

    agent.save(ckpt_path)
    csv_file.close()
    env.close()
    print(f"done. episodes: {episode}, log: {csv_path}"
          + ("" if args.random_agent else f", checkpoint: {ckpt_path}"))


if __name__ == "__main__":
    main()
